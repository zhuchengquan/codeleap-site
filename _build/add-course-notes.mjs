const esc = (s) => s;

for (const [file, cfg] of Object.entries(PAGES)) {
  const p = path.join(ROOT, file);
  let t = fs.readFileSync(p, 'utf8');

  // 幂等：移除上次插入的整块
  const startMark = t.indexOf(MARK);
  if (startMark >= 0) {
    const endMark = t.indexOf('<!-- /cn:notes -->', startMark);
    if (endMark > startMark) t = t.slice(0, startMark) + t.slice(endMark + '<!-- /cn:notes -->'.length);
  }

  const blocks = cfg.items.map(([title, body, check], i) => `    <div class="blk">
      <h3><span class="n">${String(i + 1).padStart(2, '0')}</span>${esc(title)}</h3>
      <p>${esc(body)}</p>
      <div class="hours">${esc(check)}</div>
    </div>`).join('\n');

  const section = `${MARK}
  <section class="sec">
    <div class="sec-head">
      <span>家长视角</span>
      <h2>最容易误判的三件事</h2>
      <p>${esc(cfg.lead)}</p>
    </div>
    <div class="blocks">
${blocks}
    </div>
  </section>
<!-- /cn:notes -->

`;

  const anchor = '  <section class="cta">';
  if (!t.includes(anchor)) { console.error(`${file}: cta anchor missing`); continue; }
  t = t.replace(anchor, section + anchor);
  fs.writeFileSync(p, t, 'utf8');
  console.log(`${file}: notes section inserted (${(Buffer.byteLength(t) / 1024).toFixed(1)} KB)`);
}
