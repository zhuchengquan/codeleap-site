for (const [file, d] of Object.entries(DATA)) {
  const p = path.join(root, file);
  let html = fs.readFileSync(p, 'utf8');
  if (html.includes('id="ps-class"')) { console.log('skip', file); continue; }

  // shift ps4..ps8 -> ps5..ps9
  for (let n = 8; n >= 4; n--) {
    html = html.split(`id="ps${n}"`).join(`id="ps${n + 1}"`);
  }

  const head = `    <div class="sec-head">
      <span>课堂实录</span>
      <h2 id="ps4">这一级到底练什么：三个课堂片段</h2>
      <p>${d.lead}</p>
    </div>`;
  const snips = d.snips.map(([t, body], i) =>
    `<div class="blk"><h3><span class="n">0${i + 1}</span>${t}</h3><p>${body}</p></div>`).join('');
  const can = d.can.map(([b, s]) =>
    `<div class="work"><b>${b}</b><span>${s}</span></div>`).join('');

  const sec = `  <section class="sec">
${head}
    <div class="blocks">${snips}</div>
    <div class="works" style="grid-template-columns:repeat(2,1fr);margin-top:14px">${can}</div>
    <p style="margin-top:14px;font-size:13.5px;line-height:1.75;color:var(--muted)">${d.notYet}</p>
  </section>

`;

  const anchor = html.indexOf('<h2 id="ps5"');
  const start = html.lastIndexOf('<section class="sec">', anchor);
  html = html.slice(0, start) + sec + html.slice(start);
  fs.writeFileSync(p, html, 'utf8');
  console.log('inserted', file);
}
